#!/usr/bin/env node

const MODAL_ENDPOINT_URL = 'https://ntclick--phonezoo-acestep-generate.modal.run'
const ACCOUNT = '0xdf66cf59a7d7bd10a9904518d17880226d03c66894c26bebaf1c35b0ba0c2757'

async function testModalPolling() {
  const jobId = `song-${Date.now()}`
  const expectedShelbyUrl = `https://api.shelbynet.shelby.xyz/shelby/v1/blobs/${ACCOUNT}/phonezoo/ringtones/ai-generated/${jobId}.mp3`

  console.log(`[1] Dispatching Modal GPU ACESTEP job: ${jobId}...`)

  const dispatchRes = await fetch(MODAL_ENDPOINT_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      prompt: 'Cyberpunk synthwave 80s beat with heavy synth drums',
      lyrics: '',
      duration: 10,
      seed: Math.floor(Math.random() * 2_147_483_647),
      job_id: jobId,
      webhook_url: 'https://phonezoo.com/api/music/webhook',
    }),
  })

  console.log(`[2] Modal Dispatch Status: ${dispatchRes.status}`)

  console.log(`[3] Waiting for Modal GPU to generate real AI audio & save to ShelbyNet...`)
  console.log(`    Shelby Blob URL: ${expectedShelbyUrl}\n`)

  const start = Date.now()
  for (let i = 1; i <= 25; i++) {
    await new Promise(r => setTimeout(r, 2000))
    const elapsed = ((Date.now() - start) / 1000).toFixed(1)

    try {
      const checkRes = await fetch(expectedShelbyUrl, { method: 'HEAD' })
      console.log(`    [Attempt ${i}/25 - ${elapsed}s] Shelby HTTP Status: ${checkRes.status}`)

      if (checkRes.ok) {
        console.log(`\n🎉 REAL AI MUSIC GENERATED BY MODAL GPU & STORED ON SHELBYNET!`)
        console.log(`   URL: ${expectedShelbyUrl}`)
        console.log(`   Time: ${elapsed}s`)
        return
      }
    } catch (e) {
      console.log(`    [Attempt ${i}/25 - ${elapsed}s] Checking...`)
    }
  }

  console.log(`\nTimed out waiting for Modal GPU blob`)
}

testModalPolling()
